func testCommandFileState(config *Config) *multistep.BasicStateBag {
	state := new(multistep.BasicStateBag)
	state.Put("config", config)
	state.Put("ui", &packer.MockUi{})
	state.Put("console_port", 4001)
	state.Put("http_ip", "127.0.0.1")
	state.Put("http_port", 8080)
	return state
}

func TestStepCreateCommandFile_BasicGenerated(t *testing.T) {
	dir := t.TempDir()
	trueVal := true

	config := &Config{
		OutputDirectory:    dir,
		VMName:             "test-vm",
		ConsoleBindAddress: "127.0.0.1",
		ConsoleLog:         &trueVal,
	}

	state := testCommandFileState(config)

	step := &stepCreateCommandFile{}
	action := step.Run(context.Background(), state)

	if action != multistep.ActionContinue {
		if err, ok := state.GetOk("error"); ok {
			t.Fatalf("expected ActionContinue, got error: %s", err)
		}
		t.Fatal("expected ActionContinue")
	}

	cmdPath := state.Get("command_file_path").(string)
	content, err := os.ReadFile(cmdPath)
	if err != nil {
		t.Fatal(err)
	}

	text := string(content)

	// Check header.
	if !strings.Contains(text, "; Generated by packer-plugin-simh") {
		t.Error("missing header comment")
	}

	// Check console config: SIMH needs two separate SET CONSOLE TELNET= commands.
	if !strings.Contains(text, "SET CONSOLE TELNET=127.0.0.1:4001\n") {
		t.Error("missing console telnet host:port config")
	}
	if !strings.Contains(text, "SET CONSOLE TELNET=BUFFERED\n") {
		t.Error("missing console telnet BUFFERED config")
	}

	// Check console log.
	if !strings.Contains(text, "SET CONSOLE LOG=") {
		t.Error("missing console log config")
	}

	// Check BOOT CPU.
	if !strings.Contains(text, "BOOT CPU") {
		t.Error("missing BOOT CPU")
	}

	// Check QUIT.
	if !strings.Contains(text, "QUIT") {
		t.Error("missing QUIT")
	}

	// QUIT should be the last non-empty line.
	lines := strings.Split(strings.TrimSpace(text), "\n")
	lastLine := strings.TrimSpace(lines[len(lines)-1])
	if lastLine != "QUIT" {
		t.Errorf("expected QUIT as last line, got %q", lastLine)
	}
}

