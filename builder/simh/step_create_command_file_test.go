func TestStepCreateCommandFile_ExternalCommandFile(t *testing.T) {
	dir := t.TempDir()
	trueVal := true

	// Create external command file.
	extFile := filepath.Join(t.TempDir(), "external.simh")
	_ = os.WriteFile(extFile, []byte("SET CPU MicroVAX\nBOOT CPU\n"), 0644)

	config := &Config{
		OutputDirectory:    dir,
		VMName:             "test-vm",
		ConsoleBindAddress: "127.0.0.1",
		ConsoleLog:         &trueVal,
		CommandFile:        extFile,
		// These should be ignored when command_file is set.
		CPUType: "SomeOtherCPU",
	}

	state := testCommandFileState(config)

	step := &stepCreateCommandFile{}
	step.Run(context.Background(), state)

	cmdPath := state.Get("command_file_path").(string)
	content, _ := os.ReadFile(cmdPath)
	text := string(content)

	// Should contain console config (two separate SET CONSOLE TELNET= commands).
	if !strings.Contains(text, "SET CONSOLE TELNET=") || !strings.Contains(text, "SET CONSOLE TELNET=BUFFERED") {
		t.Error("missing console config in external command file mode")
	}

	// Should contain external file contents.
	if !strings.Contains(text, "SET CPU MicroVAX") {
		t.Error("missing external file content")
	}

	// Should NOT contain the ignored CPU type.
	if strings.Contains(text, "SomeOtherCPU") {
		t.Error("ignored config field should not appear")
	}

	// Should end with QUIT.
	if !strings.Contains(text, "QUIT") {
		t.Error("missing QUIT")
	}
}

